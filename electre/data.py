"""Исходные данные задачи и шкала перевода качественных оценок в числа.

Вариант 3: выбирается площадка для строительства нового предприятия.
Рассматриваются шесть площадок и три критерия — дорожная сеть, энергоснабжение
и затраты на подготовку к строительству.
"""

from __future__ import annotations

from dataclasses import dataclass, field

# Шкала Харрингтона переводит словесную оценку в число от 0 до 1.
# Для каждой словесной оценки взята середина соответствующего диапазона шкалы.
HARRINGTON = {
    "очень плохо": (0.00, 0.20, 0.10),
    "плохо": (0.20, 0.36, 0.28),
    "удовлетворительно": (0.36, 0.63, 0.50),
    "хорошо": (0.63, 0.80, 0.70),
    "отлично": (0.80, 1.00, 0.90),
}

# Словесные оценки из условия и их место на шкале Харрингтона.
# Если две площадки получили одинаковую словесную оценку, но одна из них лучше,
# ей назначается большее число внутри того же диапазона шкалы.
WORD_VALUES = {
    "плохая": 0.28,
    "плохое": 0.28,
    "средняя": 0.50,
    "среднее": 0.50,
    "развитая": 0.70,
    "хорошее": 0.70,
    "развитая (немного лучше, чем у Пл3)": 0.75,
    "очень хорошее": 0.90,
}


@dataclass
class Criterion:
    """Критерий оценки альтернатив."""

    name: str
    kind: str                 # «качественный» или «числовой»
    better: str               # «больше» или «меньше» — какое значение считается лучшим
    unit: str = ""

    @property
    def maximize(self) -> bool:
        return self.better == "больше"


@dataclass
class Task:
    """Условие задачи: альтернативы, критерии, оценки и мнения экспертов."""

    title: str
    alternatives: list[str]
    criteria: list[Criterion]
    values: list[list]                       # оценки: строка — критерий, столбец — альтернатива
    expert_scores: list[list[float]]         # баллы экспертов критериям: строка — эксперт
    expert_notes: list[str] = field(default_factory=list)

    def numeric_values(self) -> list[list[float]]:
        """Оценки в числовом виде: словесные заменяются числами по шкале Харрингтона."""
        rows = []
        for criterion, row in zip(self.criteria, self.values):
            if criterion.kind == "качественный":
                rows.append([WORD_VALUES[str(value)] for value in row])
            else:
                rows.append([float(value) for value in row])
        return rows


def variant_3() -> Task:
    """Задание 3: выбор площадки для строительства предприятия."""
    return Task(
        title="Выбор площадки для строительства нового предприятия (вариант 3)",
        alternatives=["Пл1", "Пл2", "Пл3", "Пл4", "Пл5", "Пл6"],
        criteria=[
            Criterion("Дорожная сеть", "качественный", "больше"),
            Criterion("Энергоснабжение", "качественный", "больше"),
            Criterion("Затраты на подготовку", "числовой", "меньше", "млн ден. ед."),
        ],
        values=[
            ["средняя", "плохая", "развитая", "развитая (немного лучше, чем у Пл3)", "средняя", "плохая"],
            ["хорошее", "хорошее", "плохое", "среднее", "очень хорошее", "среднее"],
            [3.5, 2.5, 3.0, 3.5, 3.0, 2.0],
        ],
        # Баллы по пятибалльной шкале: чем важнее критерий, тем выше балл.
        # Эксперт 1: важнее всего затраты, дорожная сеть и энергоснабжение равны между собой.
        # Эксперт 2: важнее всего дорожная сеть, затем затраты, затем энергоснабжение.
        expert_scores=[
            [3, 3, 5],
            [5, 3, 4],
        ],
        expert_notes=[
            "Эксперт 1: наиболее важный критерий — затраты на подготовку к строительству, "
            "дорожная сеть и энергоснабжение менее важны и одинаковы между собой.",
            "Эксперт 2: наиболее важный критерий — дорожная сеть, немного менее важный — "
            "затраты на подготовку, ещё немного менее важный — энергоснабжение.",
        ],
    )
